#!/usr/bin/env node
/**
 * scripts/security-scan.mjs — section G guardrails
 * ---------------------------------------------------------------------------
 * A static scan for the mistakes that are easy to reintroduce and expensive to
 * notice: an unguarded mutating route, a secret leaking into the client bundle,
 * `unsafe-inline` sneaking back into the CSP, a raw innerHTML, a missing
 * timeout on a database call.
 *
 * Run with:  npm run security
 * Exits 1 on any finding, so it can gate a deploy.
 */
import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";

const findings = [];
const add = (level, file, message) => findings.push({ level, file, message });

function walk(dir, ext = [".ts", ".tsx"], out = []) {
  for (const entry of readdirSync(dir)) {
    if (["node_modules", ".next", ".git", "dist", "build"].includes(entry)) continue;
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) walk(path, ext, out);
    else if (ext.some((e) => path.endsWith(e))) out.push(path);
  }
  return out;
}

const source = walk(".");

/* 1 ── every mutating API route must authorise ---------------------------------- */
for (const file of source.filter((f) => f.startsWith("app/api") && f.endsWith("route.ts"))) {
  const body = readFileSync(file, "utf8");
  const mutating = /export async function (POST|PATCH|PUT|DELETE)/.test(body);
  if (!mutating) continue;

  const guarded =
    /requirePermission\(|requireAdmin\(|requireStaff\(|requireUser\(/.test(body) ||
    /currentUser\(/.test(body) ||
    /verifyStreamToken/.test(body) || // token-gated stream proxy
    /auth\.signInWithPassword|supabaseAnonServer/.test(body); // credential check itself

  /* Routes that are public BY DESIGN. Each entry states why it needs no
     session — anything else that mutates is a finding. */
  const PUBLIC_BY_DESIGN = {
    "app/api/auth/login/route.ts": "credential check — the password IS the auth",
    "app/api/auth/logout/route.ts": "clears cookies; harmless without a session",
    "app/api/auth/register/route.ts": "signup, rate-limited + validated",
    "app/api/auth/otp/request/route.ts": "login by OTP, rate-limited per phone",
    "app/api/auth/otp/verify/route.ts": "login by OTP, rate-limited per phone",
    "app/api/contact/route.ts": "public contact form, rate-limited",
    "app/api/newsletter/route.ts": "public signup, rate-limited",
    "app/api/coupons/validate/route.ts": "read-only coupon check, rate-limited",
    "app/api/cart/validate/route.ts": "re-prices the cart; reads the catalogue only, never writes",
    "app/api/auth/login-help/route.ts": "post-failure help, throttled 12/5min per IP, leaks no ids",
  };
  const key = file.replace(/^\.\//, "");
  if (guarded || PUBLIC_BY_DESIGN[key]) continue;

  add("error", file, "mutating route with no session/permission check");
}

/* 2 ── service-role key must never be imported by a client component ----------- */
for (const file of source.filter((f) => f.endsWith(".tsx"))) {
  const body = readFileSync(file, "utf8");
  if (body.startsWith('"use client"') && /SUPABASE_SERVICE_ROLE_KEY|supabaseService/.test(body)) {
    add("error", file, "service-role client used inside a client component");
  }
}

/* 3 ── no secrets in the bundle: NEXT_PUBLIC_ + secret-looking name ------------ */
for (const file of source) {
  const body = readFileSync(file, "utf8");
  if (/NEXT_PUBLIC_[A-Z_]*(SECRET|SERVICE_ROLE|PRIVATE_KEY)/.test(body)) {
    add("error", file, "secret exposed through a NEXT_PUBLIC_ variable");
  }
}

/* 4 ── CSP must not allow inline scripts outside dev --------------------------- */
const middleware = readFileSync("middleware.ts", "utf8");
if (/script-src[^;]*'unsafe-inline'/.test(middleware) && !/isDev \?/.test(middleware)) {
  add("error", "middleware.ts", "script-src allows 'unsafe-inline'");
}
if (!/nonce-\$\{nonce\}/.test(middleware)) {
  add("warn", "middleware.ts", "CSP no longer uses a per-request nonce");
}

/* 5 ── raw HTML injection ------------------------------------------------------ */
/*
 * `dangerouslySetInnerHTML` is legitimate in exactly two shapes here: an
 * application/ld+json block built from our own data, and an SVG generated by
 * the QR library. Everything else is a real injection risk.
 *
 * HOW THIS IS DECIDED NOW
 * ---------------------------------------------------------------------------
 * The previous version counted `dangerouslySetInnerHTML={{` occurrences and
 * skipped the first `hits.length - commentHits` iterations — which meant one
 * innocent mention in a comment demoted a real usage to "documentation". It
 * also referenced `onlyInComment`, a variable that was never declared. That
 * path only stayed hidden because `/svg/.test(body)` short-circuited earlier:
 * a file that mentions svg anywhere in prose skipped the whole check, so the
 * reference never ran. A scanner that throws on its own code path, and hides
 * its worst false-negative behind an unrelated string match, is worse than no
 * scanner — it reports "0 errors" with authority.
 *
 * The fix parses instead of guessing:
 *   • strip comments (line + block + JSX) before looking at anything
 *   • find real JSX usages of the attribute in the stripped source
 *   • for each, require a positive justification near it
 *   • a file that only MENTIONS the attribute in prose has zero usages, so it
 *     cannot hide anything
 */
function stripComments(src) {
  return src
    .replace(/\/\*[\s\S]*?\*\//g, " ")   // /* block */
    .replace(/(^|[^:])\/\/[^\n]*/g, "$1") // // line, not part of a URL
    .replace(/\{\s*\/\*[\s\S]*?\*\/\s*\}/g, " "); // {/* jsx comment */}
}

for (const file of source) {
  if (file.includes("security-scan")) continue;

  const raw = readFileSync(file, "utf8");
  const body = stripComments(raw);

  /* Real JSX prop usage only: `attr={{` or `attr={…}`. A sentence in prose has
     no `=` and can never match. */
  const usages = body.match(/dangerouslySetInnerHTML\s*=\s*\{/g) ?? [];
  if (!usages.length) continue;

  /* Justifications, matched against the stripped body so a comment cannot vouch
     for code. They are deliberately NARROW: the old check was `/svg/.test(body)`,
     which excused any file that merely mentioned the word "svg" in prose. This
     is the difference between a check and a rubber stamp.

       • JSON-LD: the payload is `JSON.stringify`d from our own objects
       • QR SVG: `QRCode.toString()` from the `qrcode` package — it encodes the
         URL we hand it and returns a fixed-format SVG. `data.qr.svg` below comes
         from lib/qr.ts, not from a database column. */
  const isJsonLd = /application\/ld\+json|jsonLdScript/.test(body);
  /* The component does not import qrcode — lib/qr.ts does, on the server. What
     this file does is pass that SVG through unchanged, so what it can be held
     to is: the html is exactly the qr svg field, nothing concatenated. */
  const isQrSvg = /__html:\s*data\.qr\.svg\s*\}/.test(body);

  if (isJsonLd || isQrSvg) continue;

  /* Every remaining usage is reported individually, with its line number, so
     the message points at the code instead of saying "somewhere in this file". */
  const lines = body.split("\n");
  lines.forEach((line, index) => {
    if (!/dangerouslySetInnerHTML\s*=\s*\{/.test(line)) return;
    add("warn", `${file}:${index + 1}`, "dangerouslySetInnerHTML with unverified content");
  });
}

/* The scanner must not swallow its own crash: if any check above throws, the
   process must fail loudly rather than print a clean report. Node already does
   that for an uncaught throw, but only if nothing wraps main() in a try — this
   note exists so nobody adds one. */

/* 6 ── database calls must be able to time out -------------------------------- */
const dbLib = readFileSync("lib/db.ts", "utf8");
if (!/timeoutFetch/.test(dbLib)) {
  add("error", "lib/db.ts", "fetch timeout wrapper missing — a stalled query can hang a render");
}

/* 7 ── .env files must never be committed ------------------------------------- */
for (const file of source.filter((f) => f.startsWith("./.env"))) {
  if (file !== "./.env.example") add("error", file, "real environment file is in the repository");
}

/* 8 ── sessions must come from @supabase/ssr, never a hand-rolled cookie ----- */
/* The old `lib/auth.ts` (own signed cookie) is gone: sessions live in the
   Supabase auth cookies, which @supabase/ssr writes httpOnly + SameSite=Lax.
   What must never come back is a bespoke cookie carrying a user id or role. */
for (const file of ["lib/supabase/server.ts", "lib/supabase/client.ts", "middleware.ts"]) {
  if (!source.includes(`./${file}`)) continue;
  const body = readFileSync(file, "utf8");
  if (/cookies\(\)\.set\(["'](?:uid|user|role|session_id)["']/.test(body)) {
    add("error", file, "hand-rolled session cookie — use @supabase/ssr cookies");
  }
}
const serverAuth = readFileSync("lib/supabase/server.ts", "utf8");
if (!/createServerClient/.test(serverAuth)) {
  add("error", "lib/supabase/server.ts", "createServerClient() missing — sessions would not refresh");
}

/* 9 ── payment methods: the receiving numbers stay admin-managed ---------- */
/* The payment system is deliberately simple: orders carry only
   `payment_method` + `payment_status`, and the owner marks an order paid from
   the admin panel. No route may mark an order `paid` on the customer's own
   request — that path was the old manual-verification engine and is gone. */
for (const file of source.filter((f) => f.endsWith(".ts") && f.startsWith("app/api"))) {
  const body = readFileSync(file, "utf8");
  const writesPaid = /payment_status:\s*["']paid["']/.test(body);
  const isAdminOrderPatch = file.includes("api/foisal/orders");
  if (writesPaid && !isAdminOrderPatch) {
    add("error", file, 'writes payment_status: "paid" outside the admin orders patch');
  }
}

/* 10 ── the admin URL must stay in one place -------------------------------- */
/* Every link, redirect and guard must import from lib/paths.ts. A hard-coded
   "/foisal" or "/admin" literal anywhere else means changing ADMIN_PATH would
   half-work — the worst possible outcome for a hidden panel. */
const pathAllow = new Set(["lib/paths.ts", "app/robots.ts", "middleware.ts"]);
for (const file of source.filter((f) => /^(app|components|lib)\//.test(f) && /\.(ts|tsx)$/.test(f))) {
  if (pathAllow.has(file)) continue;
  const body = readFileSync(file, "utf8");
  // ignore comments — the docs mention the URLs constantly
  const code = body
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .split("\n")
    .filter((line) => !/^\s*(\/\/|\*)/.test(line))
    .join("\n");
  /* Any *literal* of the admin path — not just fetch/href — is a bug waiting
     for the day the owner changes ADMIN_PATH. Route folders and imports are
     identifiers, not strings, so they never match here. */
  if (/[`"']\/foisal(\/|["'`?])/.test(code)) {
    add("warn", file, 'hard-coded "/foisal" — import ADMIN_BASE from lib/paths.ts');
  }
  if (/[`"']\/admin(\/|["'`?])/.test(code)) {
    add("error", file, 'links to the removed "/admin" path');
  }
}

/* 11 ── the legacy URL constant must actually be the legacy URL ------------ */
/* A bulk find-and-replace once rewrote LEGACY_ADMIN_BASE to the *new* path,
   which made the middleware 404 the live admin panel. Silent, total outage of
   the panel with no error anywhere — worth a permanent guard. */
{
  const paths = readFileSync("lib/paths.ts", "utf8");
  const match = paths.match(/LEGACY_ADMIN_BASE\s*=\s*"([^"]+)"/);
  const adminPath = (process.env.NEXT_PUBLIC_ADMIN_PATH || process.env.ADMIN_PATH || "foisal");
  if (!match) {
    add("error", "lib/paths.ts", "LEGACY_ADMIN_BASE is missing");
  } else if (match[1].replace(/^\//, "") === adminPath) {
    add("error", "lib/paths.ts", "LEGACY_ADMIN_BASE equals the live admin path — the panel would 404");
  }
}

/* 12 ── no public door to the panel ---------------------------------------- */
/* The brief is explicit: no admin links anywhere in public HTML. The footer and
   the account header both used to carry one. A component under
   app/(storefront) or components/ that links to ADMIN_BASE without a role gate
   is a leak, so flag any adminHref/ADMIN_BASE reference whose file does not
   also test a staff/admin role. */
{
  const publicRoots = "^(app/\\(storefront\\)|components/(?!admin/))";
  for (const file of source.filter((f) => new RegExp(publicRoots).test(f) && /\.(ts|tsx)$/.test(f))) {
    if (file.startsWith("app/(storefront)/foisal")) continue;
    const body = readFileSync(file, "utf8");
    if (!/(ADMIN_BASE|adminHref\(|ADMIN_LOGIN_PATH)/.test(body)) continue;
    const gated =
      /isStaffRole|role === "admin"|role === "staff"|role === "manager"|can\(/.test(body);
    if (!gated) {
      add("error", file, "references the admin URL without a staff/admin gate — a public admin link leaks the hidden path");
    }
  }
}

/* 13 ── a plan may only be activated after money arrives --------------------- */
/* /api/premium/activate used to let any signed-in customer activate their own
   pending subscription — a free year of premium for anyone who read the client
   bundle. The single legitimate path is an admin approving a TrxID. */
{
  const file = "app/api/premium/activate/route.ts";
  if (existsSync(file)) {
    const body = readFileSync(file, "utf8");
    if (!/role\s*!==\s*"admin"/.test(body) && !/requireAdmin\(/.test(body)) {
      add("error", file, "activates premium without an admin check — a customer could self-activate");
    }
    if (!/duration_days/.test(body)) {
      add("error", file, "premium activation does not read plan.duration_days — the term would be wrong");
    }
  }
}

/* 14 ── reverted rev-16 controls --------------------------------------------- */
/* Each of these reverted a real, exploitable finding. They are cheap to
   reintroduce by accident (a refactor, a merge from an old branch) and silent
   when they come back, so they get a permanent guard. */

/* 14a. A private bucket must never be handed a permanent public URL.
    complaint-photos leaked exactly this way: getPublicUrl() on a bucket that
    was later made private still returns a working link for any object that was
    already public. Upload and read paths must sign instead. */
{
  const upload = "app/api/upload/route.ts";
  if (existsSync(upload)) {
    const body = readFileSync(upload, "utf8");
    if (!/PRIVATE_BUCKETS/.test(body)) {
      add("error", upload, "private-bucket handling is gone — complaint photos would get public URLs again");
    }
    if (!/createSignedUrl/.test(body)) {
      add("error", upload, "no signed URL path — a private bucket would return an unusable URL");
    }
  }
  for (const file of source.filter((f) => f.endsWith(".ts") || f.endsWith(".tsx"))) {
    if (file.includes("upload/route.ts")) continue; // the one place it is correct
    const body = readFileSync(file, "utf8");
    if (/getPublicUrl\([^)]*\)/.test(body) && /complaint/i.test(body)) {
      add("error", file, "getPublicUrl() next to a complaint photo — that bucket is private, sign it instead");
    }
  }
}

/* 14b. The viewer cap must be reserved, never counted then inserted.
    viewerCapReached() was a COUNT in its own round-trip; N parallel requests
    all passed it. Counting may exist for display, but any route that MINTS a
    session by inserting into stream_tokens reintroduces the race. */
{
  const routes = source.filter((f) => f.startsWith("app/api") && f.endsWith("route.ts"));
  for (const file of routes) {
    const body = readFileSync(file, "utf8");
    if (/\.from\(["']stream_tokens["']\)\s*\.insert\(/.test(body)) {
      add("error", file, "inserts into stream_tokens directly — use stream_reserve_slot() so the cap is atomic");
    }
  }
  const watch = "lib/watch-rights.ts";
  if (existsSync(watch) && !/stream_reserve_slot/.test(readFileSync(watch, "utf8"))) {
    add("error", watch, "viewer-slot reservation RPC is gone — the concurrent cap is a race again");
  }
}

/* 14c. TrxID validation must fail closed.
    trxMatches() used to `catch { return true }`, so one bad pattern in the
    admin panel disabled validation for every customer while the UI still read
    as if it were enforced. */
{
  const submit = "app/api/payments/submit/route.ts";
  if (existsSync(submit)) {
    const body = readFileSync(submit, "utf8");
    const catchReturnsTrue = /catch\s*(?:\([^)]*\))?\s*\{[^}]*return\s+true/.test(
      body.split("function trxMatches")[1]?.split("function")[0] ?? ""
    );
    if (catchReturnsTrue) {
      add("error", submit, "trxMatches() fails OPEN — a broken pattern would disable TrxID validation");
    }
    if (!/payment_claim/.test(body)) {
      add("error", submit, "no payment_claim() — one TrxID could be reported against several orders");
    }
  }
}

/* 14d. Wallet mutations must stay server-only.
    wallet_apply() was PUBLIC-executable with a caller-supplied user id and
    kind, i.e. anyone could credit any balance. */
{
  const sql = "supabase/sql/29_security_hardening.sql";
  if (existsSync(sql)) {
    const body = readFileSync(sql, "utf8");
    if (!/revoke all on function public\.wallet_apply[\s\S]{0,200}from public, anon, authenticated/.test(body)) {
      add("error", sql, "wallet_apply() is not revoked from public/anon/authenticated");
    }
    if (!/from public, anon, authenticated/.test(body)) {
      add("error", sql, "a revoke omits `public` — the implicit PUBLIC grant would survive");
    }
  }
}

/* report --------------------------------------------------------------------- */
const errors = findings.filter((f) => f.level === "error");
const warns = findings.filter((f) => f.level === "warn");

console.log(`\nSecurity scan — ${errors.length} error(s), ${warns.length} warning(s)\n`);
for (const f of [...errors, ...warns]) {
  const tag = f.level === "error" ? "✗" : "!";
  console.log(`  ${tag} ${f.file}\n      ${f.message}`);
}
if (!findings.length) console.log("  ✓ no findings\n");

process.exit(errors.length ? 1 : 0);
