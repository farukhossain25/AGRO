/**
 * Emits premium seed data (farms, cameras, plans) as SQL.
 *   node scripts/seed-premium-sql.mjs > supabase/seed-premium.sql
 *
 * Idempotent — safe to run on an existing database.
 */
import { allSeedCameras, seedFarms, seedPremiumPlans, seedSellers } from "../lib/seed-premium.ts";

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v === null || v === undefined || Number.isNaN(Number(v)) ? "null" : String(Number(v)));
const b = (v) => (v ? "true" : "false");
const j = (v) => (v === null || v === undefined ? "null" : `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`);
const arr = (v) => (v?.length ? `array[${v.map(q).join(",")}]::text[]` : `'{}'::text[]`);

const out = [];
out.push(`-- বিশ্বাস এগ্রো — premium / multi-vendor seed`);
out.push(`-- 5 farms · 10 cameras · ${seedPremiumPlans.length} premium plans`);
out.push(`-- Generated by scripts/seed-premium-sql.mjs — idempotent.`);
out.push("");

/* ------------------------------------------------------------- farms */
out.push("-- farms");
const farmCols = [
  "id", "slug", "name_bn", "name_en", "type", "owner_name_bn", "owner_phone", "owner_photo",
  "owner_bio_bn", "division", "district", "upazila", "address_bn", "lat", "lng", "boundary",
  "harvest_calendar", "description_bn", "story_bn", "cover", "images", "daily_output",
  "established_year", "certifications", "is_active", "is_premium", "sort_order",
];

const farmRows = seedFarms.map((f) =>
  `  (${[
    q(f.id), q(f.slug), q(f.name_bn), q(f.name_en), q(f.type),
    q(f.owner_name_bn), q(f.owner_phone), q(f.owner_photo), q(f.owner_bio_bn),
    q(f.division), q(f.district), q(f.upazila), q(f.address_bn),
    n(f.lat), n(f.lng), j(f.boundary), j(f.harvest_calendar),
    q(f.description_bn), q(f.story_bn), q(f.cover), arr(f.images),
    j(f.daily_output), n(f.established_year), arr(f.certifications),
    b(f.is_active), b(f.is_premium), n(f.sort_order),
  ].join(", ")})`
).join(",\n");

out.push(`insert into farms (${farmCols.join(", ")}) values
${farmRows}
on conflict (slug) do update set
  name_bn = excluded.name_bn,
  type = excluded.type,
  owner_name_bn = excluded.owner_name_bn,
  owner_phone = excluded.owner_phone,
  district = excluded.district,
  lat = excluded.lat,
  lng = excluded.lng,
  boundary = excluded.boundary,
  harvest_calendar = excluded.harvest_calendar,
  description_bn = excluded.description_bn,
  cover = excluded.cover,
  daily_output = excluded.daily_output,
  is_active = true;
`);

/* ----------------------------------------------------------- cameras */
out.push("-- cameras (stream_key is the MediaMTX path name, never sent to browsers)");
const camCols = [
  "id", "farm_id", "name_bn", "zone_bn", "stream_key", "protocol", "location_lat",
  "location_lng", "status", "is_active", "is_premium", "max_viewers", "sort_order",
];

out.push(`insert into cameras (${camCols.join(", ")}) values
${allSeedCameras
  .map((c) =>
    `  (${[
      q(c.id), q(c.farm_id), q(c.name_bn), q(c.zone_bn), q(c.stream_key),
      q(c.protocol), n(c.location_lat), n(c.location_lng), q(c.status),
      b(c.is_active), b(c.is_premium), n(c.max_viewers), n(c.sort_order),
    ].join(", ")})`
  )
  .join(",\n")}
on conflict (stream_key) do update set
  farm_id = excluded.farm_id,
  name_bn = excluded.name_bn,
  zone_bn = excluded.zone_bn,
  location_lat = excluded.location_lat,
  location_lng = excluded.location_lng,
  status = excluded.status,
  is_active = true;
`);

/* ------------------------------------------------------------- plans */
out.push("-- premium plans");
const planCols = [
  "id", "slug", "name_bn", "name_en", "tier", "interval", "price", "compare_price",
  "duration_days", "max_devices", "features", "is_active", "is_popular", "sort_order",
];

out.push(`insert into premium_plans (${planCols.join(", ")}) values
${seedPremiumPlans
  .map((p) =>
    `  (${[
      q(p.id), q(p.slug), q(p.name_bn), q(p.name_en), q(p.tier), q(p.interval),
      n(p.price), n(p.compare_price), n(p.duration_days), n(p.max_devices),
      j(p.features), b(p.is_active), b(p.is_popular), n(p.sort_order),
    ].join(", ")})`
  )
  .join(",\n")}
on conflict (slug) do update set
  name_bn = excluded.name_bn,
  price = excluded.price,
  compare_price = excluded.compare_price,
  duration_days = excluded.duration_days,
  max_devices = excluded.max_devices,
  features = excluded.features,
  is_active = true;
`);

/* ----------------------------------------------------------- sellers */
out.push("-- approved demo sellers");
out.push(`insert into sellers (id, slug, farm_id, name_bn, phone, email, farm_address_bn, division, district, farm_photos, product_types, payout_method, payout_number, commission_percent, status, approved_at) values
${seedSellers
  .map((se) =>
    `  (${[
      q(se.id), q(se.slug), q(se.farm_id), q(se.name_bn), q(se.phone), q(se.email),
      q(se.farm_address_bn), q(se.division), q(se.district), arr(se.farm_photos),
      arr(se.product_types), q(se.payout_method), q(se.payout_number),
      n(se.commission_percent), q(se.status), "now()",
    ].join(", ")})`
  )
  .join(",\n")}
on conflict (slug) do update set
  name_bn = excluded.name_bn,
  farm_id = excluded.farm_id,
  district = excluded.district,
  product_types = excluded.product_types,
  commission_percent = excluded.commission_percent,
  status = 'approved';
`);

out.push(`select
  (select count(*) from farms)          as farms,
  (select count(*) from cameras)        as cameras,
  (select count(*) from premium_plans)  as plans;`);

process.stdout.write(out.join("\n"));
