export function districtsOf(division: string): string[] {
  return Object.keys(divisions[division] ?? {});
}

export function upazilasOf(division: string, district: string): string[] {
  return divisions[division]?.[district] ?? [];
}

/** Normalised lookup of which division a district belongs to. */
export function divisionOfDistrict(district: string): string | null {
  const needle = district.trim();
  for (const [division, districtMap] of Object.entries(divisions)) {
    if (districtMap[needle]) return division;
  }
  return null;
}

